internal sealed record SeedTrainer(SeedUser User, string Specialization, bool Accepted);

internal sealed record SeedStudent(
    SeedUser User, string GradeLevel, string City, string School, string NationalId, bool Accepted, int JoinYear);

internal sealed record SeedGroup(
    string Key, string Name, string Description, string TrainerKey, int StartDaysAgo, string[] StudentKeys);

/// <summary>A solution a student can submit. Score/Feedback are used only once the contest has ended.</summary>
internal sealed record SeedVariant(string Text, int Score, string Feedback);

internal sealed record SeedExample(string Input, string Output, string? Explanation);

/// <summary>
/// Variants: [0] full solution, [1] full solution written differently (minor issue),
/// [2] partial solution, [3] weak attempt. Bank problems carry their model solution(s) instead.
/// </summary>
internal sealed record SeedProblem(
    string Key, string Title, string Topic, Difficulty Difficulty, string Statement, string? Constraints,
    SeedExample[] Examples, string TrainerKey, SeedVariant[] Variants, bool Published = true);

