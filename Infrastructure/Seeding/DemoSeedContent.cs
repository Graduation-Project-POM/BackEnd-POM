    string Key, string Title, string Description, string GroupKey, Difficulty Difficulty,
    int StartDayOffset, int StartHourUtc, int EndDayOffset, int EndHourUtc, string[] ProblemKeys);

internal sealed record SeedBankSubmission(string ProblemKey, string StudentKey, int VariantIndex, bool Published, int DaysAgo);

internal sealed record SeedComment(string Key, string ProblemKey, string AuthorKey, string? ParentKey, string Body, int DaysAgo);

